import pandas as pd
import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity

df = pd.read_csv("raw_skills.csv")

# Convert pipe-separated skills into space-separated for TF-IDF
df['skills_text'] = df['skills'].str.replace('|', ' ', regex=False)

print("=" * 65)
print("  DecodeLabs Project 3 — Tech Stack Recommender")
print("=" * 65)
print(f"\n Dataset Loaded: {len(df)} job roles")
print(f" Unique Skills : {len(set(' '.join(df['skills_text']).split()))}")

vectorizer = TfidfVectorizer(
    lowercase=True,
    token_pattern=r'\S+',
)
tfidf_matrix = vectorizer.fit_transform(df['skills_text'])

def get_user_input():
    print("\n" + "=" * 65)
    print("  STEP 1: ENTER YOUR SKILLS (minimum 3)")
    print("=" * 65)
    print("Example: Python, Cloud Computing, Automation\n")

    raw = input("Your skills (comma-separated): ").strip()
    skills = [s.strip() for s in raw.split(",") if s.strip()]

    if len(skills) < 3:
        print(f"\n  You entered {len(skills)} skill(s). Need at least 3 for accuracy.")
        print("Using what you entered — results may be less accurate.\n")
    return skills

def score_roles(user_skills):
    query = ' '.join(user_skills)


    user_vector = vectorizer.transform([query])

    scores = cosine_similarity(user_vector, tfidf_matrix).flatten()
    return scores

def recommend(scores, top_n=3):
    # argsort ascending → reverse for descending
    ranked_indices = scores.argsort()[::-1][:top_n]
    return [(df.iloc[i]['job_role'], df.iloc[i]['skills'], scores[i])
            for i in ranked_indices]

def display(results, user_skills):
    print("\n" + "=" * 65)
    print("   TOP 3 RECOMMENDED CAREER PATHS")
    print("=" * 65)
    print(f"  Based on your skills: {', '.join(user_skills)}\n")

    for rank, (role, skills, score) in enumerate(results, 1):
        match_pct = score * 100
        bar = "█" * int(match_pct / 5) + "░" * (20 - int(match_pct / 5))
        print(f"  {rank}. {role}")
        print(f"     Match: {match_pct:5.1f}%  [{bar}]")
        print(f"     Skills: {skills.replace('|', ', ')}\n")

    top_role = results[0][0]
    print("=" * 65)
    print(f"   Best Fit: {top_role}")
    print("=" * 65)

def main():
    while True:
        user_skills = get_user_input()
        scores = score_roles(user_skills)
        results = recommend(scores, top_n=3)
        display(results, user_skills)

        again = input("\nTry another search? (y/n): ").strip().lower()
        if again != 'y':
            print("\n Thanks for using the Tech Stack Recommender!")
            break

if __name__ == "__main__":
    main()
